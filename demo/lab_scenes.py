def _dress_destinations(stage):
    """Powder-coat look for the calibrated tray (geometry untouched, authored by isaac_scene).

    The configured blue is kept as the hue but deepened, so the tray reads as painted steel
    rather than plastic. Applied once per stage (author_lab_prop runs once per prop).
    """
    prim = stage.GetPrimAtPath("/World_Props/Looks/TrayPaint/Surface")
    if not prim or prim.GetCustomDataByKey("cascadeLabDressed"):
        return
    prim.SetCustomDataByKey("cascadeLabDressed", True)
    shader = UsdShade.Shader(prim)
    base = shader.GetInput("diffuseColor").Get() or Gf.Vec3f(.09, .27, .62)
    mean = sum(base) / 3
    shader.GetInput("diffuseColor").Set(Gf.Vec3f(*[.62 * (.82 * c + .18 * mean) for c in base]))
    shader.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(0.)
    shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(.5)
    shader.CreateInput("clearcoat", Sdf.ValueTypeNames.Float).Set(.25)
    shader.CreateInput("clearcoatRoughness", Sdf.ValueTypeNames.Float).Set(.25)


