def _hex_nut(stage, path, across_corners, height, look, *, per_side=10):
    """Hex nut: 30 degree double chamfer (the arcs on each flat), countersunk threaded bore."""
    R = across_corners / 2
    af = R * math.sqrt(3) / 2
    rc = af * .97
    h = height / 2
    tan30 = math.tan(math.radians(30))
    corners = [(R * math.cos(k * math.pi / 3), R * math.sin(k * math.pi / 3)) for k in range(6)]
    ring = []
    for k in range(6):
        (x0, y0), (x1, y1) = corners[k], corners[(k + 1) % 6]
        for s in range(per_side):
            t = s / per_side
            ring.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t))
    n = len(ring)

    def drop(x, y):
        return max(0., math.hypot(x, y) - rc) * tan30

    soup = _Soup()
    _side_wall(soup, ring, -h, h, smooth=20, tile=.05, z_of=lambda x, y: (-h + drop(x, y), h - drop(x, y)))
    circle = [(rc * math.cos(math.atan2(y, x)), rc * math.sin(math.atan2(y, x))) for x, y in ring]
    bore_r = across_corners * .21
    cs = bore_r * 1.18
    bore_top = [(cs * math.cos(math.atan2(y, x)), cs * math.sin(math.atan2(y, x))) for x, y in ring]
    for up in (True, False):
        sgn = 1 if up else -1
        # Conical chamfer between the outline and the chamfer circle.
        nrm = (.5, .866)
        for k in range(n):
            k2 = (k + 1) % n
            pts = []
            for (x, y), (cx, cy) in ((ring[k], circle[k]), (ring[k2], circle[k2])):
                a = math.atan2(y, x)
                pts.append(((x, y, sgn * (h - drop(x, y))), (nrm[0] * math.cos(a), nrm[0] * math.sin(a), sgn * nrm[1]),
                            (k / n, math.hypot(x, y) / .02)))
                pts.append(((cx, cy, sgn * h), (nrm[0] * math.cos(a), nrm[0] * math.sin(a), sgn * nrm[1]),
                            (k / n, rc / .02)))
            ids = [soup.vert(*pts[0]), soup.vert(*pts[2]), soup.vert(*pts[3]), soup.vert(*pts[1])]
            soup.poly(ids if up else ids[::-1])
        _polar_cap(soup, circle, bore_top, sgn * h, up, .02)
    soup.emit(stage, path + "/Body", look)
    # Threaded bore (inner surface, normals towards the axis), with countersinks.
    pitch, depth, levels = .0035, .0012, 24
    pts, nrms, sts, faces = [], [], [], []
    zs = [-h] + [-h + .0015 + (2 * h - .003) * i / (levels - 1) for i in range(levels)] + [h]
    for i, z in enumerate(zs):
        for k in range(n + 1):
            a = 2 * math.pi * k / n
            if i in (0, len(zs) - 1):
                rr = cs
            else:
                f = (z / pitch + a / (2 * math.pi)) % 1.
                rr = bore_r + depth * (1 - abs(2 * f - 1))
            pts.append((rr * math.cos(a), rr * math.sin(a), z))
            nrms.append((-math.cos(a), -math.sin(a), 0))
            sts.append((k / n, z / .01))
    cols = n + 1
    for i in range(len(zs) - 1):
        for k in range(n):
            a = i * cols + k
            faces.append([a, a + cols, a + cols + 1, a + 1])
    _mesh_uv(stage, path + "/Bore", pts, faces, look, st=sts, normals=nrms)


def _gear(stage, path, outer, thickness, teeth, bore, look):
    """Spur gear with curved flanks, 0.6 mm edge chamfers and a keyed bore."""
    R, root = outer / 2, outer / 2 * .84
    h, c = thickness / 2, .0006
    ring = []
    pitch = 2 * math.pi / teeth
    for t in range(teeth):
        base = pitch * t
        half_root, half_tip = pitch * .27, pitch * .13
        for k in range(3):  # root land, from mid-gap up to the flank
            ring.append((root, base - pitch / 2 + (pitch / 2 - half_root) * k / 3))
        for k in range(5):  # rising flank
            s = k / 4
            ang = base - (half_root - (half_root - half_tip) * s ** .7)
            ring.append((root + (R - root) * s, ang))
        for k in range(1, 3):  # tip land
            ring.append((R, base - half_tip + 2 * half_tip * k / 3))
        for k in range(5):  # falling flank
            s = 1 - k / 4
            ang = base + (half_root - (half_root - half_tip) * s ** .7)
            ring.append((root + (R - root) * s, ang))
    xy = [(rr * math.cos(a), rr * math.sin(a)) for rr, a in ring]
    xy = [p for i, p in enumerate(xy) if math.dist(p, xy[i - 1]) > 1e-6]
    n = len(xy)

    def inset(points, d):
        return [(x * (1 - d / math.hypot(x, y)), y * (1 - d / math.hypot(x, y))) for x, y in points]

    soup = _Soup()
    _side_wall(soup, xy, -h + c, h - c, smooth=30, tile=.03)
    top_ring = inset(xy, c)
    for up in (True, False):
        sgn = 1 if up else -1
        for k in range(n):
            k2 = (k + 1) % n
            a = [(xy[k][0], xy[k][1], sgn * (h - c)), (xy[k2][0], xy[k2][1], sgn * (h - c)),
                 (top_ring[k2][0], top_ring[k2][1], sgn * h), (top_ring[k][0], top_ring[k][1], sgn * h)]
            soup.flat(a if up else a[::-1])
    br = bore / 2
    bore_ring = []
    for x, y in top_ring:
        ang = math.atan2(y, x)
        key = abs(((ang + math.pi) % (2 * math.pi)) - math.pi) < .22
        rr = br * 1.25 if key else br
        bore_ring.append((rr * math.cos(ang), rr * math.sin(ang)))
    for up in (True, False):
        _polar_cap(soup, top_ring, bore_ring, (1 if up else -1) * h, up, .03)
    inner = list(reversed(bore_ring))
