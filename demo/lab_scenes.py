def _aim(pos, target):
    """Light/camera frame at pos whose -Z axis points at target (Z-up world)."""
    fwd = Gf.Vec3d(*(target[k] - pos[k] for k in range(3))).GetNormalized()
    up = Gf.Vec3d(0, 0, 1) if abs(fwd[2]) < .95 else Gf.Vec3d(1, 0, 0)
    right = Gf.Cross(fwd, up).GetNormalized()
    up = Gf.Cross(right, fwd).GetNormalized()
    m = Gf.Matrix4d(1)
    m.SetRow(0, Gf.Vec4d(right[0], right[1], right[2], 0))
    m.SetRow(1, Gf.Vec4d(up[0], up[1], up[2], 0))
    m.SetRow(2, Gf.Vec4d(-fwd[0], -fwd[1], -fwd[2], 0))
    m.SetRow(3, Gf.Vec4d(pos[0], pos[1], pos[2], 1))
    return m


