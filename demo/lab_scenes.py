def _paper_ball(stage, path, dimensions, look, seed=3):
    rng = random.Random(seed)
    a, b, c = (d / 2 for d in dimensions)
    segments, rings = 32, 16
    bumps = [(rng.uniform(0, 2 * math.pi), rng.uniform(-1.2, 1.2), rng.uniform(.06, .14)) for _ in range(9)]

    def crumple(phi, theta):
        k = math.cos(phi) ** .5 * (.10 * abs(math.sin(5 * theta + 3 * phi))
                                   + .06 * abs(math.sin(3 * theta - 4 * phi + 1)))
        for t0, p0, depth in bumps:
            dist = math.acos(max(-1., min(1., math.cos(phi) * math.cos(p0) * math.cos(theta - t0)
                                         + math.sin(phi) * math.sin(p0))))
            k += depth * max(0., 1 - dist / .5) ** 2
        return max(.72, min(1., 1 - k))

    points, st, faces = [], [], []
    for i in range(rings + 1):
        phi = -math.pi / 2 + math.pi * i / rings
        for j in range(segments + 1):
            theta = 2 * math.pi * j / segments
            k = crumple(phi, theta)
            points.append((a * k * math.cos(phi) * math.cos(theta), b * k * math.cos(phi) * math.sin(theta),
                           c * k * math.sin(phi)))
            st.append((j / segments, i / rings))
    cols = segments + 1
    for i in range(rings):
        for j in range(segments):
            p = i * cols + j
            faces.append([p, p + 1, p + cols + 1, p + cols])
    return _mesh_uv(stage, path, points, faces, look, st=st)


